def check_budget() -> Result:
    r = Result("budget")
    files = list(runtime_files())
    total_lines = sum(len(read_text(p).splitlines()) for p in files)

    # 只统计自研程序集（Assets/Scripts 下）；第三方包自带的 asmdef 不计入预算
    asmdefs = [p for p in SCRIPTS.rglob("*.asmdef") if p.is_file()] if SCRIPTS.exists() else []
    interfaces = 0
    iface_re = re.compile(r"^\s*(?:public|internal)?\s*(?:partial\s+)?interface\s+\w+")
    for path in files:
        for line in read_text(path).splitlines():
            if iface_re.match(line):
                interfaces += 1

    if total_lines > LIMITS["runtime_lines"]:
        r.fail("runtime", f"{total_lines} 行 > {LIMITS['runtime_lines']}（先减再加）")
    if len(files) > LIMITS["runtime_files"]:
        r.fail("runtime", f"{len(files)} 文件 > {LIMITS['runtime_files']}")
    if len(asmdefs) > LIMITS["asmdefs"]:
        r.fail("asmdef", f"{len(asmdefs)} 个 > {LIMITS['asmdefs']}（拆分门槛见 02 §1）")
    if interfaces > LIMITS["interfaces"]:
        r.fail("interface", f"{interfaces} 个 > {LIMITS['interfaces']}（R4：只在三条件下出现）")

    per_dir = {}
    for path in files:
        text = read_text(path)
        lines = len(text.splitlines())
        if lines > LIMITS["file_lines"]:
            r.fail(rel(path), f"{lines} 行 > {LIMITS['file_lines']}（先拆类型）")
        per_dir.setdefault(path.parent, []).append(path)
    for directory, members in per_dir.items():
        if len(members) > LIMITS["dir_files"]:
            r.fail(rel(directory) + "/", f"{len(members)} 个 .cs > {LIMITS['dir_files']}（先按职责分目录）")

    r.note(
        f"runtime {total_lines}/{LIMITS['runtime_lines']} 行, "
        f"{len(files)}/{LIMITS['runtime_files']} 文件; "
        f"asmdef {len(asmdefs)}/{LIMITS['asmdefs']}; "
        f"interface {interfaces}/{LIMITS['interfaces']}"
    )
    return r


