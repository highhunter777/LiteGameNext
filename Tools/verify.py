def check_structure() -> Result:
    r = Result("structure")
    dirs = 0
    if SCRIPTS.exists():
        for path in sorted(SCRIPTS.rglob("*")):
            if path.is_dir():
                dirs += 1
                if path.name.lower() in FORBIDDEN_DIRS:
                    r.fail(rel(path) + "/", f"禁用目录名 {path.name}（接口与实现同目录，02 §3.4）")

    calls = 0
    for path in iter_files(SCRIPTS, {".cs"}):
        text = read_text(path)
        for needle, message in FORBIDDEN_CALLS:
            start = 0
            while True:
                index = text.find(needle, start)
                if index < 0:
                    break
                calls += 1
                r.fail(f"{rel(path)}:{line_of(text, index)}", message)
                start = index + len(needle)

    r.note(f"{dirs} 目录；{calls} 处禁用调用")
    return r


