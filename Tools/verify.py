ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "Assets" / "Scripts"
RUNTIME_DIRS = (SCRIPTS / "Core", SCRIPTS / "Game")

# ---- 预算（AGENTS.md §1 / 01 §11）----
LIMITS = {
    "runtime_lines": 25_000,
    "runtime_files": 220,
    "asmdefs": 5,
    "interfaces": 20,
    "file_lines": 400,
    "dir_files": 20,
}

# ---- 分层（AOT 不得引用热更面）----
AOT_FORBIDDEN = re.compile(r"\bLiteGame\.(Game|Ui|Boot|Features)\b")

# ---- 结构 ----
FORBIDDEN_DIRS = {"abstractions", "utils", "helpers", "common"}
FORBIDDEN_CALLS = (("GameObject.Find(", "改走显式引用/SceneRefs，禁按名查找"),)

# ---- 卫生 ----
DEBUG_LOG = re.compile(r"\bDebug\.Log(Warning|Error|Format|Assert)?\s*\(")
LOG_SINK = "Assets/Scripts/Core/Logging/Log.cs"   # 日志门面本身，唯一允许调用 Debug.Log 的文件
EMPTY_CATCH = re.compile(r"catch\s*(?:\([^)]*\))?\s*\{\s*\}")
TODO_MARK = re.compile(r"\b(TODO|FIXME)\b")
SECRET_PATTERNS = (
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), "私钥内容"),
    (re.compile(r"gh[pousr]_[A-Za-z0-9]{36}"), "GitHub Token"),
    (re.compile(r"AKIA[0-9A-Z]{16}"), "AWS Access Key"),
    (re.compile(r"""(?i)(api[_-]?key|secret|password|access[_-]?token)\s*[:=]\s*["'][^"'\s]{16,}["']"""), "硬编码凭据"),
)
SECRET_EXCLUDES = {"verify.py"}
TEXT_EXTENSIONS = {".cs", ".json", ".md", ".py", ".txt", ".yml", ".yaml", ".asmdef", ".lua", ".shader", ".hlsl"}

# ---- 文档 ----
DESIGN_STATUS_WORDS = re.compile(r"已交付|已实施|待提交|批次[A-Z0-9]|施工记录")

# ---- 命名（02 §3.1）----
PASCAL = re.compile(r"^[A-Z][A-Za-z0-9]*$")
PRIVATE_FIELD = re.compile(r"^_[a-z][A-Za-z0-9]*$")
NAMING_BANNED = ("Mgr", "Helper", "Utils", "Common", "Tmp", "Foo", "Bar", "Baz", "Dummy")
ASYNC_RETURNS = {"UniTask", "Task", "ValueTask"}
NAMESPACE_LINE = re.compile(r"^\s*namespace\s+([A-Za-z0-9_.]+)")
TYPE_LINE = re.compile(
    r"^\s*(?:(?:public|private|protected|internal|static|sealed|abstract|partial|unsafe|new|readonly)\s+)*"
    r"(class|struct|record|interface|enum)\s+([A-Za-z_]\w*)"
)
METHOD_LINE = re.compile(
    r"^\s*(?:public|private|protected|internal)\s+"
    r"(?:(?:static|virtual|override|sealed|abstract|async|extern|unsafe|new|partial|readonly)\s+)*"
    r"([A-Za-z_][\w<>\[\],\.\?]*)\s+([A-Za-z_]\w*)\s*\("
)
FIELD_LINE = re.compile(
    r"^\s*(public|private|protected|internal)\s+"
    r"((?:(?:static|readonly|const|volatile|unsafe|new|required)\s+)*)"
    r"([A-Za-z_][\w<>\[\],\.\?]*)\s+([A-Za-z_]\w*)\s*(?:=[^;]*)?;"
)
PROPERTY_LINE = re.compile(
    r"^\s*(?:public|private|protected|internal)\s+"
    r"(?:(?:static|virtual|override|sealed|abstract|new|required)\s+)*"
    r"[A-Za-z_][\w<>\[\],\.\?]*\s+([A-Za-z_]\w*)\s*\{\s*(?:get|set)"
)
CONST_LINE = re.compile(r"^\s*const\s+[A-Za-z_][\w<>\[\],\.\?]*\s+([A-Za-z_]\w*)")


