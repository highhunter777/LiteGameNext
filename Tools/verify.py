DECL_TYPE = re.compile(r"\b(class|struct|interface|enum|record)\b")
DECL_SKIP = ("using ", "namespace ", "#", "}", "]", "{")


def check_comments() -> Result:
    r = Result("comments")
    scanned = 0
    for path in iter_files(SCRIPTS, {".cs"}):
        scanned += 1
        lines = read_text(path).splitlines()
        i = 0
        while i < len(lines):
            stripped = lines[i].strip()
            prefix = "///" if stripped.startswith("///") else ("//" if stripped.startswith("//") else None)
            if not prefix:
                i += 1
                continue
            j = i
            while j < len(lines) and lines[j].strip().startswith(prefix):
                j += 1
            block = j - i

            k = j
            while k < len(lines) and (not lines[k].strip() or lines[k].strip().startswith("[")):
                k += 1
            if k < len(lines):
                decl = lines[k].strip()
                if not decl.startswith(DECL_SKIP):
                    is_type = bool(DECL_TYPE.search(decl))
                    limit = 4 if prefix == "///" else (3 if is_type else 2)
                    if block > limit:
                        r.fail(
                            f"{rel(path)}:{i + 1}",
                            f"{prefix} 连续 {block} 行 > {limit}（类型/成员注释预算，01 §11）",
                        )
            i = j

    r.note(f"{scanned} 个 .cs")
    return r


