def rel(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def is_generated(path: Path) -> bool:
    posix = path.as_posix()
    if "/Generated/" in posix or path.name.endswith(".g.cs"):
        return True
    try:
        head = path.open(encoding="utf-8", errors="replace").read(400)
    except OSError:
        return False
    return "<auto-generated" in head


def iter_files(base: Path, suffixes, skip_generated=True):
    if not base.exists():
        return
    for path in sorted(base.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in suffixes:
            continue
        if skip_generated and is_generated(path):
            continue
        yield path


def runtime_files():
    for base in RUNTIME_DIRS:
        yield from iter_files(base, {".cs"})


def line_of(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


class Result:
    def __init__(self, name: str):
        self.name = name
        self.violations = []
        self.notes = []

    def fail(self, where: str, message: str):
        self.violations.append(f"{where}  {message}")

    def note(self, message: str):
        self.notes.append(message)

    @property
    def ok(self) -> bool:
        return not self.violations


