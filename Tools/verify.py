def check_build() -> Result:
    r = Result("build")
    csproj = ROOT / "Tests" / "LiteGame.Tests.csproj"
    if not csproj.exists():
        r.note("跳过：Tests/LiteGame.Tests.csproj 尚未创建（P0 后生效）")
        return r
    for args in (["dotnet", "build", str(csproj), "-v", "q", "-nologo"],
                 ["dotnet", "test", str(csproj), "--no-build", "-v", "q", "-nologo"]):
        proc = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
        if proc.returncode != 0:
            tail = (proc.stdout + proc.stderr).strip().splitlines()[-8:]
            r.fail(" ".join(args[:2]), "失败：" + " | ".join(tail))
            return r
    r.note("dotnet build/test 通过")
    return r


def check_shared() -> Result:
    r = Result("shared")
    manifest = ROOT / "Tools" / "sync-manifest.json"
    if not manifest.exists():
        r.note("跳过：Tools/sync-manifest.json 尚未生成（02 §6.2）")
        return r
    import hashlib

    recorded = json.loads(read_text(manifest))
    for name, digest in recorded.items():
        path = ROOT / name
        if not path.exists():
            r.fail(name, "同步清单里的文件缺失，跑 python Tools/sync_shared.py")
            continue
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != digest:
            r.fail(name, "哈希与同步清单不符，旧仓已重生成？跑 python Tools/sync_shared.py")
    r.note(f"比对 {len(recorded)} 个生成物")
    return r


def check_pipeline() -> Result:
    r = Result("pipeline")
    package = ROOT / "Packages" / "com.unity.pipeline"
    required = (
        "package.json",
        "Editor/Unity.Pipeline.Editor.asmdef",
        "Runtime/Unity.Pipeline.asmdef",
        "Editor/AnalyticInfoCompat_2022.cs",
    )
    if not package.exists():
        r.fail("Packages/com.unity.pipeline/", "缺失：python Tools/restore_pipeline.py（02 §5.1）")
    else:
        for item in required:
            if not (package / item).exists():
                r.fail(f"Packages/com.unity.pipeline/{item}", "包不完整，重跑 restore_pipeline.py")

    if not shutil.which("unity"):
        r.fail("unity CLI", "不在 PATH：需安装 unity-pipeline CLI，否则无法驱动编辑器（02 §5.1）")

    if r.ok:
        r.note("包已就位（官方 0.7.0-exp.1 + 2022.3 补丁）；CLI 在 PATH")
    return r


