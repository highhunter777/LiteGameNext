def check_hygiene() -> Result:
    r = Result("hygiene")
    scanned = 0
    for path in iter_files(SCRIPTS, {".cs"}):
        posix = rel(path)
        if "/Editor/" in "/" + posix or "/Tests/" in "/" + posix:
            continue
        scanned += 1
        text = read_text(path)
        if posix != LOG_SINK:
            for match in DEBUG_LOG.finditer(text):
                r.fail(f"{posix}:{line_of(text, match.start())}", "生产路径禁 Debug.Log*，改用 Log.*（01 §10）")
        for match in EMPTY_CATCH.finditer(text):
            r.fail(f"{posix}:{line_of(text, match.start())}", "空 catch —— 要么处理要么抛出（01 §10）")
        for match in TODO_MARK.finditer(text):
            r.fail(f"{posix}:{line_of(text, match.start())}", "TODO/FIXME 悬挂：改成「待办批次」或直接做完")

    secrets = 0
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in TEXT_EXTENSIONS:
            continue
        parts = set(path.parts)
        if parts & {".git", "Library", "Temp", "Logs", "UserSettings", "Bundles", "obj", "bin", "__pycache__"}:
            continue
        if path.name in SECRET_EXCLUDES:
            continue
        try:
            if path.stat().st_size > 512 * 1024:
                continue
        except OSError:
            continue
        text = read_text(path)
        for pattern, label in SECRET_PATTERNS:
            match = pattern.search(text)
            if match:
                secrets += 1
                r.fail(f"{rel(path)}:{line_of(text, match.start())}", f"疑似{label}，移出仓库并用环境变量")

    r.note(f"{scanned} 个生产 .cs；密钥命中 {secrets}")
    return r


