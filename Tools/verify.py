def check_layers() -> Result:
    r = Result("layers")
    core = SCRIPTS / "Core"
    scanned = 0
    for path in iter_files(core, {".cs"}):
        scanned += 1
        text = read_text(path)
        for match in AOT_FORBIDDEN.finditer(text):
            r.fail(f"{rel(path)}:{line_of(text, match.start())}", f"AOT 侧出现 {match.group(0)}（01 §15 H1）")

    for path in iter_files(core, {".asmdef"}, skip_generated=False):
        try:
            data = json.loads(read_text(path))
        except json.JSONDecodeError:
            r.fail(rel(path), "asmdef 不是合法 JSON")
            continue
        for ref in data.get("references", []):
            if "LiteGame.Game" in ref:
                r.fail(rel(path), f"Core.asmdef 引用了 {ref}（01 §15 H3）")

    r.note(f"core {scanned} 文件；无 Game 引用" if r.ok else f"core {scanned} 文件")
    return r


