LINK = re.compile(r"\]\(([^)\s]+)")
SKIP_LINK_PREFIX = ("http://", "https://", "mailto:", "#")


def check_docs() -> Result:
    r = Result("docs")
    docs = [ROOT / "README.md"] if (ROOT / "README.md").exists() else []
    docs += sorted((ROOT / "Docs").rglob("*.md")) if (ROOT / "Docs").exists() else []

    links = 0
    for path in docs:
        text = read_text(path)
        for match in LINK.finditer(text):
            target = match.group(1)
            if target.startswith(SKIP_LINK_PREFIX) or not target:
                continue
            links += 1
            target_path = (path.parent / target.split("#")[0]).resolve()
            if not target_path.exists():
                r.fail(f"{rel(path)}:{line_of(text, match.start())}", f"链接失效：{target}")

    design_dir = ROOT / "Docs" / "设计文档"
    checked = 0
    if design_dir.exists():
        for path in sorted(design_dir.rglob("*.md")):
            checked += 1
            text = read_text(path)
            for match in DESIGN_STATUS_WORDS.finditer(text):
                r.fail(
                    f"{rel(path)}:{line_of(text, match.start())}",
                    f"设计文档出现施工状态词「{match.group(0)}」（状态只写进度卷，01 元数据）",
                )

    # 文档预算（01 §11）：篇数 ≤ 8 / 行数 ≤ 2,000（含根 README.md、AGENTS.md）
    all_docs = list(docs)
    for name in ("AGENTS.md",):
        path = ROOT / name
        if path.exists():
            all_docs.append(path)
    total_lines = sum(len(read_text(p).splitlines()) for p in all_docs)
    if len(all_docs) > 8:
        r.fail("docs", f"{len(all_docs)} 篇 > 8（文档预算，01 §11）")
    if total_lines > 2_000:
        r.fail("docs", f"{total_lines} 行 > 2,000（文档预算，01 §11）")

    r.note(f"{len(all_docs)} 篇文档 / {total_lines} 行 / {links} 条相对链接；设计文档 {checked} 篇")
    return r


